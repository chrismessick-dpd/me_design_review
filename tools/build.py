# Shared Signoff engine (EE and ME). Edit it in ee_design_review only; me_design_review
# vendors it unchanged with tools/sync_engine.py. Tool specifics go in assets/config.js.
"""Build a Signoff tool (EE or ME): validate templates, bundle them, and stamp the version.

Run this after changing anything in templates/, index.html or assets/, before committing:

    python tools/build.py           # rebuild assets/templates.js and assets/version.js
    python tools/build.py --check   # exit 1 if either is stale (CI / pre-commit)

assets/templates.js lets the tool work when index.html is opened straight from disk
(browsers block fetch() on file://). assets/version.js holds a hash of the tool files;
after a sync the app compares it with the repo's copy and says when a newer tool exists.
Asset URLs in index.html get ?v=<hash> so browsers load fresh files after an update.
"""
import datetime
import hashlib
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TEMPLATES = ROOT / "templates"
BUNDLE = ROOT / "assets" / "templates.js"
VERSION = ROOT / "assets" / "version.js"
HTML = ROOT / "index.html"
ASSET_URL = re.compile(r'((?:src|href)="assets/[^"?]+)(\?v=[0-9a-fx]*)?(")')


def load_config():
    """assets/config.js: window.SIGNOFF_CONFIG = {strict JSON};"""
    text = (ROOT / "assets" / "config.js").read_text(encoding="utf-8")
    return json.loads(re.search(r"window\.SIGNOFF_CONFIG\s*=\s*(\{.*\})\s*;", text, re.S).group(1))


def bundle_text():
    order = load_config().get("templateOrder", [])
    templates = [json.loads(p.read_text(encoding="utf-8")) for p in TEMPLATES.glob("*.json")]
    templates.sort(key=lambda t: (order.index(t["id"]) if t["id"] in order else len(order), t["id"]))
    body = json.dumps(templates, ensure_ascii=False, separators=(",", ":"))
    return ("/* Generated by tools/build.py from templates/*.json - do not edit by hand. */\n"
            "window.SIGNOFF_TEMPLATES = " + body + ";\n")


def tool_files():
    files = [HTML] + [p for p in (ROOT / "assets").rglob("*") if p.is_file() and p != VERSION]
    return sorted(files, key=lambda p: p.relative_to(ROOT).as_posix())


def content_hash(bundle):
    h = hashlib.sha256()
    for path in tool_files():
        data = bundle.encode("utf-8") if path == BUNDLE else path.read_bytes()
        data = data.replace(b"\r\n", b"\n")
        if path == HTML:
            data = ASSET_URL.sub(r"\1\3", data.decode("utf-8")).encode("utf-8")
        h.update(path.relative_to(ROOT).as_posix().encode() + b"\0" + data + b"\0")
    return h.hexdigest()[:12]


def current_hash():
    if not VERSION.exists():
        return None
    m = re.search(r"hash:\s*'([0-9a-f]+)'", VERSION.read_text(encoding="utf-8"))
    return m.group(1) if m else None


def main(argv):
    check = "--check" in argv
    # A tool that vendors the shared engine (Signoff ME) must have an up-to-date copy.
    sync = ROOT / "tools" / "sync_engine.py"
    if sync.exists() and subprocess.call([sys.executable, str(sync), "--check"]) != 0:
        return 1
    if subprocess.call([sys.executable, str(ROOT / "tools" / "validate_templates.py")], stdout=subprocess.DEVNULL) != 0:
        subprocess.call([sys.executable, str(ROOT / "tools" / "validate_templates.py")])
        return 1
    bundle = bundle_text()
    stale_bundle = not BUNDLE.exists() or BUNDLE.read_text(encoding="utf-8") != bundle
    if not check and stale_bundle:
        BUNDLE.write_text(bundle, encoding="utf-8", newline="\n")
    digest = content_hash(bundle)
    html = HTML.read_text(encoding="utf-8")
    stamped = ASSET_URL.sub(lambda m: m.group(1) + "?v=" + digest + m.group(3), html)
    if check:
        stale = stale_bundle or current_hash() != digest or stamped != html
        print("stale - run python tools/build.py" if stale else "up to date (" + digest + ")")
        return 1 if stale else 0
    if stamped != html:
        HTML.write_text(stamped, encoding="utf-8", newline="\n")
    if current_hash() != digest:
        VERSION.write_text(
            "/* Generated by tools/build.py - do not edit by hand. */\n"
            "window.SIGNOFF_VERSION = { hash: '%s', date: '%s' };\n" % (digest, datetime.date.today().isoformat()),
            encoding="utf-8", newline="\n")
    n = bundle.count('"severity"')
    print("built %s: %d checks in %s" % (digest, n, BUNDLE.relative_to(ROOT).as_posix()))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
